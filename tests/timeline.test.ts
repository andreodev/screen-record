import assert from 'node:assert/strict';
import {clipRanges,editedDuration,editedToSource,sourceToEdited,splitClip,formatTime} from '../src/timeline.ts';
const split = splitClip([{start:0,end:10}],3)!;
assert.deepEqual(split,[{start:0,end:3},{start:3,end:10}]);
assert.equal(splitClip(split,3),null);
assert.equal(splitClip(split,.02),null);
const kept=clipRanges({start:1,end:9},[{start:0,end:3},{start:5,end:10}]);
assert.equal(editedDuration(kept),6);
assert.equal(sourceToEdited(4,kept),2);
assert.equal(editedToSource(2,kept),5);
assert.equal(editedToSource(6,kept),9);
assert.equal(editedToSource(-1,kept),1);
assert.equal(editedToSource(10,kept),9);
for(const source of [1,2.5,5,8,9])assert.ok(Math.abs(editedToSource(sourceToEdited(source,kept),kept)-source)<1e-8);
assert.deepEqual(clipRanges({start:4,end:4.5},[{start:0,end:3},{start:5,end:10}]),[]);
assert.equal(formatTime(59.9999),'1:00.000');
assert.equal(formatTime(3599.9999),'60:00.000');
assert.equal(formatTime(-1),'0:00.000');
console.log('Timeline checks passed: splits, deleted gaps, trims, clock rollover.');

const variable = [{start: 0, end: 2, speed: 2, hideCursor: true}, {start: 4, end: 6, speed: .5, cursorOriginal: true}];
assert.equal(editedDuration(variable), 5);
assert.equal(sourceToEdited(1, variable), .5);
assert.equal(editedToSource(1, variable), 4);
assert.equal(editedToSource(3, variable), 5);
for (const t of [0, .5, 1, 2, 4, 5]) assert.ok(Math.abs(sourceToEdited(editedToSource(t, variable), variable) - t) < 1e-8);
assert.deepEqual(splitClip(variable, 1)?.slice(0, 2), [{start: 0, end: 1, speed: 2, hideCursor: true}, {start: 1, end: 2, speed: 2, hideCursor: true}]);
assert.deepEqual(clipRanges({start: 1, end: 5}, variable), [{start: 1, end: 2, speed: 2, hideCursor: true, index: 0}, {start: 4, end: 5, speed: .5, cursorOriginal: true, index: 1}]);
console.log('Clip settings passed: variable-speed time mapping and settings preserved across trim/split.');
